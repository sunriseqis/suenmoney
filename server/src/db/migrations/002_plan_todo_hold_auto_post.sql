-- ---------------------------------------------------------------------------
-- 002: 待办的「本期不再自动入账」标记
-- ---------------------------------------------------------------------------
-- 这一列是「撤销确认」与「恢复跳过」能成立的前提，不是可选的润色。
--
-- `settleAutoPost` 的选取条件是 `status = 'pending' AND repayment_date <= today`。
-- 撤销 = 把待办改回 pending。没有这一列时，用户撤销一笔自动入账的房贷，
-- 下次打开首页 `settleAutoPost` 立刻又把它入账 —— 界面表现是「撤销按了没用，
-- 过一会儿它自己回来了」，而且**不报错**，因为每一步在 SQL 层面都是合法的。
--
-- 「恢复跳过」同理：被跳过的期次几乎总是已经到期的，恢复成 pending 的那一瞬间
-- 就满足 `repayment_date <= today`，会被当场自动入账，用户看到的是「恢复后直接变成已付」。
--
-- 语义：`hold_auto_post = 1` 表示**这一期被用户显式地从自动入账里摘出来了**，
-- 只能靠手动「确认」入账。它由「撤销」与「恢复跳过」置 1；
-- 之后不会自动清 0 —— 改计划时待办整批重建，新行默认 0，这才是「重新开始」的时机。
-- 手动确认不把它清 0：清掉会埋一个「撤销过的手动确认，某天又被自动入账」的隐性反悔。
--
-- SQLite 的 ALTER TABLE ADD COLUMN 要求 NOT NULL 必须带 DEFAULT，这里给了 0，
-- 存量待办因此全部落在「照旧自动入账」上，行为不变。
ALTER TABLE plan_todos ADD COLUMN hold_auto_post INTEGER NOT NULL DEFAULT 0;
