-- ---------------------------------------------------------------------------
-- 003: 待办的「我知道了」标记（确认提醒）
-- ---------------------------------------------------------------------------
-- 为什么需要这一列：提醒列表里有两类期次，它们要的动作**不是同一种**。
--
--   · 这一期**会**自动入账（`plans.auto_post = 1` 且 `hold_auto_post = 0`）
--     → 用户能做的只有「我知道了」。他不需要、也不该手动入账，
--       因为到还款日 `settleAutoPost` 自己会把账做掉。
--   · 这一期**不会**自动入账（计划没开，或这一期被撤销过）
--     → 用户必须做决定：「入账」（生成那笔支出）或「忽略」（这一期不记了）。
--
-- 第二类有现成的落点（`confirmTodo` / `skipTodo`）。第一类不能复用它们：
--
--   · 复用「入账」= 把到还款日才会发生的事提前做掉，账目日期与计划不符；
--   · 复用「忽略」= `skipTodo` 会把状态改成 `skipped`，而 `settleAutoPost`
--     只挑 `status = 'pending'` 的行 —— 于是「别提醒我」变成了
--     **偷偷把自动入账关掉**，那笔账从此永远不入，且不报错。
--
-- 所以第一类只能有一个**纯知悉、不改业务状态**的动作，它需要一个落点。
--
-- 语义：`ack_at` 非空 = 用户已经看过并认可这一期了。
--   · 它**不改变** `status`（仍是 `pending`），到还款日照旧自动入账；
--   · 它**只影响**「该处理了」列表的过滤条件 —— 列表排除 `ack_at IS NOT NULL`。
--
-- 为什么落库而不是放前端 localStorage：换设备 / 换浏览器之后提醒会重新冒出来，
-- 用户看到的是「点了没用」，而每一次都要重新点一遍。
--
-- 什么时候会被清回 NULL：
--   · 撤销一次确认（`revertTodoConfirm`）—— 那一期回到 `pending` 且被摘出自动入账，
--     它必须重新出现在提醒里等用户处理；
--   · 恢复一个被跳过的期次（`restoreSkippedTodo`）—— 同理。
--   两者都必须清：不清的话，一度被「确认」过的期次在撤销后**再也不会提醒**，
--   用户会以为撤销失败了。
--
-- SQLite 的 ALTER TABLE ADD COLUMN 允许可空列不带 DEFAULT，
-- 存量待办因此全部落在「未确认」上，行为与加这一列之前一致。
ALTER TABLE plan_todos ADD COLUMN ack_at TEXT;
