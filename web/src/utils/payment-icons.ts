export const LUCIDE_ICONS: Record<string, Component> = {
  cash: Banknote,
  creditcard: CreditCard,
  bank: Landmark,
  wallet: Wallet,
};

export function resolvePaymentIcon(
  name: string,
  explicitIcon?: string,
): { id: PaymentIconId; color: string } {
  const explicit = explicitIcon?.trim().toLowerCase();
  if (explicit) {
    const match = PAYMENT_ICON_OPTIONS.find((opt) => opt.id === explicit);
    if (match) return match;
  }

  const n = (name ?? '').toLowerCase();
  if (n.includes('支付宝') || n.includes('花呗') || n.includes('alipay')) {
    return { id: 'alipay', color: '#1677FF' };
  }
  if (n.includes('微信') || n.includes('财付通') || n.includes('wechat') || n.includes('wx')) {
    return { id: 'wechat', color: '#07C160' };
  }
  if (n.includes('银联') || n.includes('云闪付') || n.includes('unionpay')) {
    return { id: 'unionpay', color: '#D83B01' };
  }
  if (n.includes('京东') || n.includes('白条') || n.includes('jd')) {
    return { id: 'jd', color: '#E1251B' };
  }
  if (n.includes('抖音') || n.includes('douyin')) {
    return { id: 'douyin', color: '#111827' };
  }
  if (n.includes('现金') || n.includes('cash')) {
    return { id: 'cash', color: '#10B981' };
  }
  if (n.includes('信用卡') || n.includes('贷记卡') || n.includes('credit')) {
    return { id: 'creditcard', color: '#F59E0B' };
  }
  if (n.includes('储蓄卡') || n.includes('借记卡') || n.includes('银行卡') || n.includes('卡')) {
    return { id: 'card', color: '#4F46E5' };
  }
  if (n.includes('银行') || n.includes('转账') || n.includes('汇款')) {
    return { id: 'bank', color: '#2563EB' };
  }
  return { id: 'card', color: '#6366F1' };
}
